"""Claude Code: the generated CLAUDE.md stub and the format hook."""

from collections.abc import Iterator
from pathlib import Path

from setups_manager.checks.links import relink
from setups_manager.context import Context
from setups_manager.model import Fix, Result, Status
from setups_manager.registry import check


def stub_imports(text: str) -> list[Path]:
    return [
        Path(line[1:].strip()) for line in text.splitlines() if line.startswith("@")
    ]


@check("claude", "setup", "Claude Code instructions and format hook")
def claude(ctx: Context) -> Iterator[Result]:
    stub = ctx.home / ".claude" / "CLAUDE.md"
    text = stub.read_text(encoding="utf-8") if stub.is_file() else ""
    imports = stub_imports(text)
    private_context = ctx.private / "claude" / "context.md"
    if "Generated by Setups" not in text:
        yield Result(
            "CLAUDE.md is not the generated stub", Status.WARN, str(stub), relink(ctx)
        )
    elif dead := [str(p) for p in imports if not p.exists()]:
        yield Result(
            "CLAUDE.md imports missing files", Status.WARN, "\n".join(dead), relink(ctx)
        )
    elif private_context.is_file() and not any(
        p.resolve() == private_context.resolve() for p in imports
    ):
        yield Result(
            "Setups-private is cloned but CLAUDE.md does not import it",
            Status.WARN,
            fix=relink(ctx),
        )
    else:
        yield Result(f"CLAUDE.md stub imports {len(imports)} files", Status.OK)

    settings = ctx.home / ".claude" / "settings.json"
    if settings.is_file() and "format_hook.py" in settings.read_text(encoding="utf-8"):
        yield Result("format hook registered", Status.OK)
    else:
        hook = ctx.setups / "common" / "lint" / "format_hook.py"
        fix = Fix(f"Register {hook} as a PostToolUse hook in ~/.claude/settings.json")
        yield Result("format hook not registered", Status.WARN, str(settings), fix)
