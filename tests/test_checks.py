import subprocess

import pytest
from setups_manager.checks import claude, links, repos, vscode
from setups_manager.model import Status


def statuses(results):
    return [r.status for r in results]


def test_lint_configs_match_then_drift(ctx):
    lint = ctx.setups / "common" / "lint"
    lint.mkdir(parents=True)
    for name in links.LINT_FILES:
        (lint / name).write_text(f"# {name}\n")
        (ctx.home / name).write_text(f"# {name}\n")
    assert statuses(links.lint_configs(ctx)) == [Status.OK]

    (ctx.home / "ruff.toml").write_text("changed\n")
    [result] = links.lint_configs(ctx)
    assert result.status is Status.WARN
    assert result.detail == "ruff.toml"
    assert result.fix and result.fix.command == ctx.link_script()


def write_stub(ctx, *imports):
    stub = ctx.home / ".claude" / "CLAUDE.md"
    stub.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "<!-- Generated by Setups test -->",
        *(f"@{p.as_posix()}" for p in imports),
    ]
    stub.write_text("\n".join(lines) + "\n")


def test_claude_stub_ok_missing_import_and_private_not_imported(ctx):
    rules = ctx.setups / "common" / "claude" / "rules.md"
    rules.parent.mkdir(parents=True)
    rules.write_text("rules\n")
    write_stub(ctx, rules)
    first = next(iter(claude.claude(ctx)))
    assert (first.status, first.title) == (Status.OK, "CLAUDE.md stub imports 1 files")

    write_stub(ctx, rules, ctx.home / "gone.md")
    assert "missing files" in next(iter(claude.claude(ctx))).title

    context = ctx.private / "claude" / "context.md"
    context.parent.mkdir(parents=True)
    context.write_text("me\n")
    write_stub(ctx, rules)
    assert "does not import it" in next(iter(claude.claude(ctx))).title


def test_claude_hand_written_file_is_flagged(ctx):
    (ctx.home / ".claude").mkdir(parents=True)
    (ctx.home / ".claude" / "CLAUDE.md").write_text("# my notes\n")
    results = list(claude.claude(ctx))
    assert results[0].title == "CLAUDE.md is not the generated stub"
    assert results[1].title == "format hook not registered"


@pytest.mark.parametrize(
    ("item", "status", "fix_args"),
    [
        (
            {"status": "ok", "subject": "Python", "detail": "22 extensions"},
            Status.OK,
            None,
        ),
        (
            {
                "status": "drift",
                "subject": "settings.json",
                "detail": "has local changes",
            },
            Status.WARN,
            ["--diff"],
        ),
        (
            {"status": "extra", "subject": "Default", "detail": "x.y"},
            Status.WARN,
            ["--prune"],
        ),
        (
            {"status": "missing", "subject": "profile Rust", "detail": ""},
            Status.WARN,
            [],
        ),
        (
            {"status": "failed", "subject": "Default", "detail": "boom"},
            Status.ERROR,
            None,
        ),
    ],
)
def test_vscode_setup_results_map_to_fixes(item, status, fix_args):
    setup = ["python", "setup.py"]
    result = vscode.convert(item, setup)
    assert result.status is status
    if fix_args is None:
        assert result.fix is None or result.fix.command is None
    else:
        assert result.fix and result.fix.command == [*setup, *fix_args]
    if item["status"] == "ok":
        assert result.title == "Python: 22 extensions"


def git(repo, *args):
    subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True)


@pytest.fixture
def git_identity(monkeypatch):
    for var in ("GIT_AUTHOR_NAME", "GIT_COMMITTER_NAME"):
        monkeypatch.setenv(var, "Test")
    for var in ("GIT_AUTHOR_EMAIL", "GIT_COMMITTER_EMAIL"):
        monkeypatch.setenv(var, "test@example.com")


def test_repos_clean_dirty_and_missing(ctx, git_identity):
    ctx.setups.mkdir(parents=True)
    git(ctx.setups, "init", "-q", "-b", "main")
    (ctx.setups / "a.txt").write_text("a\n")
    git(ctx.setups, "add", "-A")
    git(ctx.setups, "commit", "-q", "-m", "init")

    def result_for(repo):
        return next(r for r in repos.repos(ctx) if r.title.startswith(str(repo)))

    clean = result_for(ctx.setups)
    assert clean.status is Status.OK
    assert clean.detail == "uncommitted: 0, unpushed: no remote"
    assert result_for(ctx.private).status is Status.WARN  # not cloned

    (ctx.setups / "a.txt").write_text("changed\n")
    dirty = result_for(ctx.setups)
    assert dirty.status is Status.WARN
    assert "1 uncommitted" in dirty.title
